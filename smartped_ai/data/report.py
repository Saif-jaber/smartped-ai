from __future__ import annotations

from collections import Counter
from pathlib import Path

from .models import ValidationIssue


def _markdown_cell(value: object) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ")


def render_validation_report(
    totals: dict,
    issues: list[ValidationIssue],
    split_manifest: dict,
    output_dir: Path,
) -> str:
    errors = [issue for issue in issues if issue.severity == "error"]
    warnings = [issue for issue in issues if issue.severity == "warning"]
    lines = [
        "# SmartPed AI Dataset Validation Report",
        "",
        "Generated by the SmartPed AI PIE ingestion pipeline. No video frames are extracted.",
        "",
        "## Result",
        "",
        f"- **Status:** {'FAIL' if errors else 'PASS'}",
        f"- **Errors:** {len(errors)}",
        f"- **Warnings:** {len(warnings)}",
        f"- **Output directory:** `{output_dir}`",
        "",
        "## Dataset statistics",
        "",
        f"- Videos: **{totals['videos']}**",
        f"- Video frames (metadata or XML task-size fallback): **{totals['video_frames']:,}**",
        f"- Annotated frame indices: **{totals['annotated_frames']:,}**",
        f"- Pedestrian tracks: **{totals['pedestrian_tracks']:,}**",
        f"- Vehicle tracks: **{totals['vehicle_tracks']:,}**",
        f"- Visible pedestrian boxes: **{totals['pedestrian_boxes']:,}**",
        f"- Visible vehicle boxes: **{totals['vehicle_boxes']:,}**",
        f"- Pedestrian intention records: **{totals['intention_annotations']:,}**",
        f"- Ego telemetry frame records: **{totals['ego_telemetry_frames']:,}**",
        "",
        "### Per-set coverage",
        "",
        "| Set | Videos | Video frames | Annotated frames | Pedestrian tracks | Vehicle tracks | Intention records |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for set_id, stats in sorted(totals["sets"].items()):
        lines.append(
            f"| {set_id} | {stats['videos']} | {stats['video_frames']:,} | "
            f"{stats['annotated_frames']:,} | {stats['pedestrian_tracks']:,} | "
            f"{stats['vehicle_tracks']:,} | {stats['intention_annotations']:,} |"
        )

    lines.extend(["", "### Object and label counts", ""])
    for heading, values in (
        ("Visible boxes by category", totals["object_boxes_by_category"]),
        ("Pedestrian action labels", totals["action_labels"]),
        ("Frame-level crossing labels", totals["crossing_labels"]),
        ("Per-track crossing outcomes", totals["crossing_outcomes"]),
    ):
        lines.extend([f"#### {heading}", "", "| Label | Count |", "|---|---:|"])
        if values:
            for label, count in sorted(values.items()):
                lines.append(f"| `{_markdown_cell(label)}` | {count:,} |")
        else:
            lines.append("| _No records_ | 0 |")
        lines.append("")

    intention = totals["intention_probability"]
    lines.extend(
        [
            "#### Intention probability",
            "",
            f"- Count: {intention['count']:,}",
            f"- Mean: {intention['mean']}",
            f"- Median: {intention['median']}",
            f"- Range: {intention['min']}–{intention['max']}",
            "",
            "### Grouped splits",
            "",
            "| Split | Sets | Videos | Video frames | Pedestrian tracks | Vehicle tracks |",
            "|---|---|---:|---:|---:|---:|",
        ]
    )
    for split_name, stats in split_manifest["statistics"].items():
        lines.append(
            f"| {split_name} | {', '.join(stats['sets']) or '—'} | {stats['videos']} | "
            f"{stats['video_frames']:,} | {stats['pedestrian_tracks']:,} | "
            f"{stats['vehicle_tracks']:,} |"
        )
    lines.extend(["", "Split limitations:"])
    lines.extend(f"- {item}" for item in split_manifest["limitations"])
    lines.extend(["", "## Issues", ""])

    if issues:
        counts = Counter((issue.severity, issue.code) for issue in issues)
        lines.extend(["| Severity | Code | Count |", "|---|---|---:|"])
        for (severity, code), count in sorted(counts.items()):
            lines.append(f"| {severity.upper()} | `{code}` | {count} |")
        lines.extend(
            [
                "",
                "### Issue details",
                "",
                "| Severity | Code | Video | Frame | Track ID | Location | Message |",
                "|---|---|---|---:|---|---|---|",
            ]
        )
        for issue in issues[:200]:
            lines.append(
                "| "
                + " | ".join(
                    _markdown_cell(value or "—")
                    for value in (
                        issue.severity,
                        issue.code,
                        issue.video_id,
                        issue.frame_index,
                        issue.track_id,
                        issue.path,
                        issue.message,
                    )
                )
                + " |"
            )
        if len(issues) > 200:
            lines.extend(
                [
                    "",
                    f"Details are limited to the first 200 issues here; "
                    f"all {len(issues)} issues are available in `validation_issues.json`.",
                ]
            )
    else:
        lines.append("No validation errors or warnings were detected.")

    lines.extend(
        [
            "",
            "## Recommendations and interpretation",
            "",
            "- Review all errors before creating training examples; warnings require interpretation.",
            "- PIE spatial annotations cover selected interacting objects, not necessarily every visible object.",
            "- Keep all clips from a recording set in one split. Six sets provide limited independent "
            "validation/test groups; report grouped cross-validation or per-set results when practical.",
            "- `intention_prob` is a soft human-aggregated intention target and is distinct from observed "
            "crossing action/outcome.",
            "- No collision-risk labels are supplied. Treat future risk estimates as derived proxies until "
            "validated against a reviewed event set.",
            "",
        ]
    )
    return "\n".join(lines)
